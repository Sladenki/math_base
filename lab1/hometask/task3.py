import numpy as np

# Фиксируем генератор, чтобы результат повторялся
rng = np.random.default_rng(42)

# Случайная матрица 100×5
X = rng.random((100, 5))

# Новый столбец: col6 = col1 + col2
col6 = X[:, 0] + X[:, 1]
X6 = np.column_stack((X, col6))

print('Размер новой матрицы:', X6.shape)

# Ранг после добавления столбца
rank_X6 = np.linalg.matrix_rank(X6)
print('Ранг матрицы 100x6:', rank_X6)

# Ранг матрицы X^T X (она размера 6x6)
XTX = X6.T @ X6
rank_XTX = np.linalg.matrix_rank(XTX)
print('Ранг X^T X:', rank_XTX)

# col6 = col1 + col2, это линейная комбинация уже имеющихся столбцов,
# поэтому ранг равен 5, а не 6. Ранг X^T X совпадает с рангом X.
# Для МНК матрица X^T X должна быть обратимой, здесь она вырожденная,
# значит обычную регрессию по всем 6 столбцам построить нельзя.
print('Ранг равен 5, потому что 6-й столбец зависит от первых двух.')
print('Регрессию по всем столбцам построить нельзя: X^T X вырожденная.')
